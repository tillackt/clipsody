import AppKit
import ClippboardCore

/// Polls the general pasteboard; macOS offers no change notification for it.
@MainActor
final class ClipboardMonitor {
    private let store: Store
    private let config: () -> Config
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    var onChange: (() -> Void)?

    // Markers from nspasteboard.org that password managers and similar tools set.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(store: Store, config: @escaping () -> Config) {
        self.store = store
        self.config = config
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    /// Call after writing to the pasteboard ourselves so that write is not recorded again.
    func ignoreCurrentContents() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        if types.contains(where: { Self.skippedTypes.contains($0.rawValue) }) { return }

        let config = config()
        let app = NSWorkspace.shared.frontmostApplication
        if let bundleId = app?.bundleIdentifier, config.ignoredApps.contains(bundleId) { return }
        let appName = app?.localizedName
        let appPath = app?.bundleURL?.path

        // Files copied in Finder are pasted back as files, not as path text.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            store.addFiles(urls.map(\.path), app: appName, appPath: appPath)
        } else if let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            store.addText(text, rich: Self.richText(from: pasteboard), app: appName, appPath: appPath)
        } else if config.keepImages,
                  let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            guard let image = ImageIngest.prepare(data) else { return }
            store.addImage(image, app: appName, appPath: appPath)
        } else {
            return
        }
        onChange?()
    }

    /// Formatting pasted with ⏎: RTF from Office/Pages/TextEdit, otherwise HTML from browsers.
    private static func richText(from pasteboard: NSPasteboard) -> RichText? {
        let maxBytes = 5_000_000
        for type in [NSPasteboard.PasteboardType.rtf, .html] {
            if let data = pasteboard.data(forType: type), data.count <= maxBytes {
                return RichText(data: data, type: type.rawValue)
            }
        }
        return nil
    }
}
